def _asset_stats_table(stats_df: pd.DataFrame, out_dir: Path) -> None:
    """Write one combined ETF identity, category, and performance longtable."""
    # Ticker is the stable join key when a public display name is corrected.
    indexed = stats_df.set_index("ticker")

    lines: list[str] = [
        "% Auto-generated by scripts/generate_thesis_numbers.py",
        "% Sources: src/asset_universe.ETF_UNIVERSE and",
        "%          results/tables/asset_descriptive_statistics.csv",
        "% Do not edit by hand.",
        r"{\scriptsize",
        r"\setlength{\tabcolsep}{2.8pt}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\begin{longtable}{@{}p{2.15cm}p{1.55cm}p{1.80cm}rrrr@{}}",
        r"\caption{ETF 资产类型与历史表现}\label{tab:asset_stats}\\",
        r"\toprule",
        r"ETF & 代码 & 类别 & 样本数 & 年化收益 & 年化波动 & 最大回撤 \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"ETF & 代码 & 类别 & 样本数 & 年化收益 & 年化波动 & 最大回撤 \\",
        r"\midrule",
        r"\endhead",
    ]

    current_section: str | None = None
    has_short_history = False
    for etf in ETF_UNIVERSE:
        section = _etf_section(etf)
        if section != current_section:
            current_section = section
            lines.append(f"% {section}")

        name = etf.new_name
        if etf.ticker not in indexed.index:
            logger.warning("ETF %s (%s) missing from stats CSV; skipping", name, etf.ticker)
            continue

        row = indexed.loc[etf.ticker]
        obs = int(row["available_observations"])
        ret = _pct(float(row["annualized_return"]))
        vol = _pct(float(row["annualized_volatility"]))
        mdd = _pct(float(row["max_drawdown"]))

        if obs < _SHORT_HISTORY_OBS:
            obs_str = f"{obs}$^*$"
            has_short_history = True
        else:
            obs_str = str(obs)

        lines.append(
            f"{name} & {etf.ticker} & {section} & {obs_str} & "
            f"{ret} & {vol} & {mdd} \\\\"
        )

    lines.append(r"\bottomrule")
    if has_short_history:
        lines.append(
            r"\multicolumn{7}{@{}l}{\footnotesize $^*$ 近期上市 ETF，"
            r"可用历史较短，仅在积累足够观测后参与优化。} \\"
        )
    lines += [r"\end{longtable}", r"}", ""]

    out_path = out_dir / "generated_asset_stats_table.tex"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    logger.info("wrote asset stats table -> %s", out_path)



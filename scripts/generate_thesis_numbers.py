def _write_fallback(out_dir: Path) -> None:
    """Write generated_fallback.tex with \\providecommand for all optional macros."""
    lines = [
        "% Auto-generated fallback definitions. Do not edit by hand.",
        "% Placeholder values compile the thesis before all pipeline outputs exist.",
        "",
    ]
    for name in _FALLBACK_MACROS:
        lines.append(f"\\providecommand{{\\{name}}}{{?}}")
    lines.append("")
    out_path = out_dir / "generated_fallback.tex"
    # Use Unix line endings to avoid LaTeX CR+LF parsing issues.
    out_path.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    logger.info("wrote fallback definitions -> %s", out_path)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")
    summary_path = resolve_path("results/tables/convex_adaptive_performance_summary.csv")
    if not Path(summary_path).exists():
        raise FileNotFoundError(
            f"performance summary not found at {summary_path}; run scripts/run_convex_adaptive_rrp.py first"
        )
    summary = pd.read_csv(summary_path)

    stats_path = resolve_path("results/tables/asset_descriptive_statistics.csv")
    if not Path(stats_path).exists():
        raise FileNotFoundError(
            f"asset stats not found at {stats_path}; run the full pipeline first"
        )
    stats_df = pd.read_csv(stats_path)

    freq_path = resolve_path("results/tables/rebalance_frequency_sensitivity.csv")
    if not Path(freq_path).exists():
        raise FileNotFoundError(
            f"rebalance frequency sensitivity not found at {freq_path}; "
            "run scripts/run_rebalance_frequency_sensitivity.py first"
        )
    freq_df = pd.read_csv(freq_path)

    first_date, last_date = _manifest_dates()
    out_dir = Path(resolve_path("report/thesis_latex"))
    out_dir.mkdir(parents=True, exist_ok=True)

    # Write the standalone table .tex files and fallback definitions.
    _etf_pool_table(out_dir)
    _asset_stats_table(stats_df, out_dir)
    _rebalance_frequency_table(freq_df, out_dir)
    _write_fallback(out_dir)

    header = [
        "% ===========================================================",
        "%  Auto-generated by scripts/generate_thesis_numbers.py",
        f"%  Generated at (UTC):     {datetime.now(tz=timezone.utc).isoformat()}",
        "%  Sources:",
        "%    - results/tables/convex_adaptive_performance_summary.csv",
        "%    - results/tables/asset_descriptive_statistics.csv",
        "%    - results/tables/rebalance_frequency_sensitivity.csv",
        "%    - results/tables/sharpe_difference_tests.csv (optional)",
        "%    - data/MANIFEST.json (optional, for evaluation dates)",
        "%  Do not edit by hand. Run the generator script after every",
        "%  pipeline rerun to keep thesis numbers in sync with the CSVs.",
        "% ===========================================================",
        "",
    ]
    if first_date is not None:
        header.append(f"\\newcommand{{\\dataFirstDate}}{{{first_date}}}")
    if last_date is not None:
        header.append(f"\\newcommand{{\\dataLastDate}}{{{last_date}}}")
    monthly_rf = load_monthly_risk_free()
    effective = monthly_rf[
        monthly_rf["effective_month"].between(
            pd.Timestamp(_EVAL_START_DATE).to_period("M"),
            pd.Timestamp(_EVAL_END_DATE).to_period("M"),
        )
    ]
    if effective.empty:
        raise ValueError("No monthly risk-free rates cover the evaluation period.")
    header.append(f"\\newcommand{{\\riskFreeRate}}{{{_pct(float(effective['annual_yield'].mean()))}}}")
    header.append(f"\\newcommand{{\\riskFreeRateMin}}{{{_pct(float(effective['annual_yield'].min()))}}}")
    header.append(f"\\newcommand{{\\riskFreeRateMax}}{{{_pct(float(effective['annual_yield'].max()))}}}")
    header.append("")

    content = (
        header
        + _eval_period_macros(first_date, last_date)
        + _percent_summary_rows(summary)
        + _rebalance_frequency_rows(freq_df)
        + _asset_stat_macros(stats_df)
        + _walkforward_rows()
        + _breakeven_rows()
        + _vol_aligned_rows()
        + _sharpe_diff_rows()
        + _latest_diagnostic_rows()
    )
    out_path = out_dir / "generated_numbers.tex"
    out_path.write_text("\n".join(content) + "\n", encoding="utf-8")
    logger.info("wrote %d lines -> %s", len(content), out_path)


if __name__ == "__main__":
    main()
